"""Convert UI color literals to fallback-preserving tokens, then build dark values.

Run again after changing CSS. Physical rack rendering, branding and transparent
shadows are excluded from palette conversion. Normal/light colors never change.
"""
from pathlib import Path
import colorsys,re
ROOT=Path(__file__).resolve().parents[1]
FILES=['style.css','theme.css','maps.css','marketplace.css','help.css']
TOKEN=re.compile(r'var\(--atlas-(bg|fg|border|shadow)-([0-9a-f]{6,8}),\s*(#[0-9a-fA-F]{3,8}|white|black)\)')
COLOR=re.compile(r'#[a-fA-F0-9]{8}\b|#[a-fA-F0-9]{6}\b|#[a-fA-F0-9]{4}\b|#[a-fA-F0-9]{3}\b|\bwhite\b|\bblack\b')
PHYSICAL=re.compile(r'\.(?:rack-device|equipment-face|mount-ear|rack-elevation|rack-rail|rack-unit|vertical-pdu|device-photo|device-image|brand-mark|port-slot|port-square|rack-floor)(?:[\s.:#>+\[]|$)')
colors={}
def rgb(value):
 if value=='white':value='#ffffff'
 if value=='black':value='#000000'
 value=value[1:].lower()
 if len(value) in (3,4):value=''.join(c*2 for c in value)
 if len(value) not in (6,8):return None
 return value,tuple(int(value[i:i+2],16)/255 for i in (0,2,4))
def convert(value,role):
 parsed=rgb(value)
 if not parsed:return value
 hex,components=parsed;h,l,s=colorsys.rgb_to_hls(*components)
 if role=='bg':
  if l<.8:return value
  if s<.11:h,s=210/360,.23
  else:s=min(.35,max(.18,s*.6))
  l=.14+(1-l)*.33
 elif role=='border':
  if l<.35:return value
  if s<.15:h,s=210/360,.22
  else:s=min(s,.32)
  l=.28 if l>.7 else .38
 elif role=='fg':
  if l>.73:return value
  if s<.15:h,s=210/360,.16
  else:s=min(.85,max(.3,s))
  l=max(.73,min(.86,1-l*.3))
 else:return value
 result='#'+''.join(f'{round(c*255):02x}' for c in colorsys.hls_to_rgb(h,l,s))+hex[6:]
 token='--atlas-'+role+'-'+hex;colors[token]=result
 return 'var('+token+', '+value+')'
for name in FILES:
 path=ROOT/'static'/name;source=path.read_text()
 # Restore literals first so repeated generation remains deterministic.
 source=TOKEN.sub(lambda m:m[3],source)
 def rule(match):
  selectors,body=match.groups()
  if ':root' in selectors or PHYSICAL.search(selectors):return match[0]
  def declaration(m):
   prop,value=m.groups();lower=prop.strip().lower()
   role='bg' if lower in ('background','background-color','background-image') else 'border' if lower.startswith('border') or lower=='outline' else 'fg' if lower in ('color','fill','stroke') else None
   if role:value=COLOR.sub(lambda c:convert(c[0],role),value)
   return prop+':'+value
  return selectors+'{'+re.sub(r'([^;{}:]+):([^;{}]+)',declaration,body)+'}'
 path.write_text(re.sub(r'([^{}]+)\{([^{}]*)\}',rule,source))
base='''/* Generated by scripts/build-appearance-palette.py. Light fallbacks remain in source CSS. */
:root{color-scheme:light}
html[data-theme="dark"]{color-scheme:dark;--bg:#101821;--surface:#1b2531;--ink:#e2eaf3;--muted:#acbacb;--line:#35465a;--accent:#3478df;--light-green:#1c304c;--asset-border:#35465a;
'''
base+=''.join(k+':'+v+';\n' for k,v in sorted(colors.items()))+'}\n'
base+='''
html[data-theme="dark"] input,html[data-theme="dark"] select,html[data-theme="dark"] textarea{background-color:#17212d;color:var(--ink);border-color:var(--line)}
html[data-theme="dark"] .workspace-search input,html[data-theme="dark"] .market-search input{background:transparent}
html[data-theme="dark"] dialog{background:var(--surface);color:var(--ink);border-color:var(--line)}
html[data-theme="dark"] dialog::backdrop{background:#000a}
html[data-theme="dark"] .unit-number{color:#b2c0c9}
html[data-theme="dark"] .market-logo>span{background:color-mix(in srgb,var(--package-color) 18%,#1b2531);color:color-mix(in srgb,var(--package-color) 60%,white)}
.topbar-actions{display:flex;align-items:center;gap:10px;flex-shrink:0}.appearance-menu{position:relative;font-size:12px}.appearance-menu>summary{list-style:none;cursor:pointer;border:1px solid var(--line);border-radius:8px;padding:9px 14px;background:var(--surface);color:var(--ink);min-width:65px;text-align:center}.appearance-menu>summary::-webkit-details-marker{display:none}.appearance-menu>summary:focus-visible{outline:3px solid #72b5ce;outline-offset:3px}.appearance-menu[open]{z-index:40}.appearance-options{position:absolute;right:0;top:calc(100% + 9px);width:260px;background:var(--surface);color:var(--ink);border:1px solid var(--line);border-radius:12px;padding:16px;box-shadow:0 12px 34px #0003;z-index:40}.appearance-options strong{display:block;margin-bottom:12px;font-size:13px}.appearance-options [role="group"]{display:flex;gap:6px}.appearance-options button{flex:1;border:1px solid var(--line);border-radius:7px;background:var(--bg);padding:9px;color:var(--ink);font-size:12px}.appearance-options button[aria-pressed="true"]{background:var(--accent);border-color:var(--accent);color:white}.appearance-options small{display:block;margin-top:12px;color:var(--muted);font-size:11px}.topbar:has(.appearance-menu[open]){z-index:30}
@media(prefers-reduced-motion:reduce){*,*::before,*::after{scroll-behavior:auto!important;transition:none!important}}
'''
(ROOT/'static/appearance.css').write_text(base)
print('Generated',len(colors),'adaptive interface colors; original light colors preserved.')
